#!/usr/bin/env python3
"""Generate the shared API17-compatible display-only translation catalog."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "shared/src/com/veloster/i18n/UiText.java"


def generated():
    entries = json.loads((ROOT / "translations/en.json").read_text(encoding="utf-8"))
    korean = json.loads((ROOT / "translations/ko.json").read_text(encoding="utf-8"))
    def literal(value):
        return json.dumps(value, ensure_ascii=False)
    def table(name, values):
        return "\n".join("        " + name + ".put(" + literal(k) + "," + literal(v) + ");" for k, v in sorted(values.items()))
    return '''// Generated by scripts/generate_translations.py. Edit translations/*.json instead.
package com.veloster.i18n;

import java.util.HashMap;
import java.util.Locale;
import java.util.Map;

/** Display strings only. Never changes Locale defaults, signal IDs or stored values. */
public final class UiText {
    private static final Map<String,String> EN=new HashMap<String,String>();
    private static final Map<String,String> KO=new HashMap<String,String>();
    private static volatile String language=resolve("auto",Locale.getDefault().getLanguage());
    static {
''' + table("EN", entries) + "\n" + table("KO", korean) + '''
    }
    private UiText() {}
    public static String selection(String selected){return "ko".equals(selected)||"en".equals(selected)?selected:"auto";}
    public static String resolve(String selected,String system){
        String choice=selection(selected);
        if(!"auto".equals(choice))return choice;
        return system!=null&&(system.equalsIgnoreCase("ko")||system.toLowerCase(Locale.US).startsWith("ko-")||system.toLowerCase(Locale.US).startsWith("ko_"))?"ko":"en";
    }
    public static void configure(String selected,String system){language=resolve(selected,system);}
    public static String language(){return language;}
    public static String t(String key){
        if(key==null)return "";
        String value=("ko".equals(language)?KO:EN).get(key);
        return value==null?key:value;
    }
    public static String[] list(String[] keys){String[] result=new String[keys.length];for(int i=0;i<keys.length;i++)result[i]=t(keys[i]);return result;}
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generated()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            raise SystemExit("Translation catalog is stale. Run scripts/generate_translations.py")
        print("Translation catalog matches the language files.")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
